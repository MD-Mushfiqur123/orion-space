/**
 * Searches the 64 districts registry for any match against the input text.
 * Performs normalized substring and alias lookup.
 * @param {string} text Raw or lowercased search query
 * @returns {object|null} District sector object or null if not found
 */
export function findDistrictSector(text) {
  if (!text || typeof text !== 'string') return null;
  const q = text.toLowerCase().trim();

  // 1. Direct exact or alias match
  for (const key of Object.keys(BANGLADESH_DISTRICTS)) {
    const d = BANGLADESH_DISTRICTS[key];
    if (d.id === q || d.name.toLowerCase() === q || (d.bnName && d.bnName === q)) {
      return d;
    }
    if (d.aliases && d.aliases.some(alias => alias.toLowerCase() === q)) {
      return d;
    }
  }

  // 2. Substring match inside query (e.g. "fly to pirojpur", "where is pirojpur", "পিরোজপুরের খবর কি")
  for (const key of Object.keys(BANGLADESH_DISTRICTS)) {
    const d = BANGLADESH_DISTRICTS[key];
    if (q.includes(d.id) || (d.bnName && q.includes(d.bnName))) {
      return d;
    }
    if (d.aliases && d.aliases.some(alias => q.includes(alias.toLowerCase()))) {
      return d;
    }
  }

  return null;
}
